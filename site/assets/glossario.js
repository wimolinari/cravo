/* ============================================================
   Comportamento dos tooltips
   Marcação no HTML: <span class="term" data-term="redobro">Redobro</span>
   ============================================================ */

(function () {
  let activeTooltip = null;
  let tooltipEl = null;

  function ensureTooltip() {
    if (!tooltipEl) {
      tooltipEl = document.createElement('div');
      tooltipEl.className = 'tooltip';
      document.body.appendChild(tooltipEl);
    }
    return tooltipEl;
  }

  function showTooltip(termEl) {
    const key = termEl.dataset.term;
    const entry = window.GLOSSARIO[key];
    if (!entry) return;

    const tip = ensureTooltip();
    tip.innerHTML = '<strong>' + entry.titulo + '</strong>'
      + (entry.original ? '<span class="original-term">' + entry.original + '</span>' : '')
      + entry.descricao;

    // Position
    const rect = termEl.getBoundingClientRect();
    const tipRect = { width: 320, height: 0 };
    let left = rect.left + window.scrollX + rect.width / 2 - tipRect.width / 2;
    left = Math.max(10, Math.min(left, window.innerWidth - tipRect.width - 10));
    let top = rect.bottom + window.scrollY + 8;

    tip.style.left = left + 'px';
    tip.style.top = top + 'px';
    tip.classList.add('visible');

    // If goes below viewport, flip above
    requestAnimationFrame(() => {
      const tr = tip.getBoundingClientRect();
      if (tr.bottom > window.innerHeight - 10) {
        tip.style.top = (rect.top + window.scrollY - tr.height - 8) + 'px';
      }
    });

    activeTooltip = termEl;
  }

  function hideTooltip() {
    if (tooltipEl) tooltipEl.classList.remove('visible');
    activeTooltip = null;
  }

  function init() {
    // Make terms keyboard-accessible
    document.querySelectorAll('.term').forEach(el => {
      if (!el.hasAttribute('tabindex')) el.setAttribute('tabindex', '0');
      el.setAttribute('role', 'button');
      el.setAttribute('aria-haspopup', 'true');

      el.addEventListener('mouseenter', () => showTooltip(el));
      el.addEventListener('mouseleave', hideTooltip);
      el.addEventListener('focus', () => showTooltip(el));
      el.addEventListener('blur', hideTooltip);
      el.addEventListener('click', (e) => {
        e.preventDefault();
        if (activeTooltip === el) hideTooltip(); else showTooltip(el);
      });
    });

    // Close on escape or outside click
    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') hideTooltip();
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
